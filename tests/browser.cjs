// Optional browser smoke test; requires Playwright and Chromium on the host.
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const { mkdtempSync, rmSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const net = require('node:net');
const assert = require('node:assert/strict');
(async () => {
  const listener = net.createServer();
  await new Promise(r => listener.listen(0, '127.0.0.1', r));
  const port = listener.address().port;
  await new Promise(r => listener.close(r));
  const data = mkdtempSync(join(tmpdir(), 'wish-browser-'));
  const server = spawn('python3', ['server.py'], {cwd:resolve(__dirname, '..'), env:{...process.env, WISHLIST_DATA:data, PORT:String(port), WISHNEST_SAMPLE_PRODUCTS:'0'}, stdio:'pipe'});
  const base = `http://127.0.0.1:${port}`;
  let browser;
  try {
    let ready = false;
    for (let i=0;i<100;i++) {
      try { const r = await fetch(base+'/api/status'); if(r.ok){ready=true;break;} } catch {}
      await new Promise(r => setTimeout(r, 50));
    }
    assert(ready, 'Test server started');
    browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless:true, args:['--no-sandbox']});
    const parent = await browser.newPage({viewport:{width:1280,height:900}});
    parent.setDefaultTimeout(10000);
    const errors = [];
    parent.on('pageerror', error => errors.push(error.message));
    await parent.goto(base);
    await parent.getByRole('button', {name:'Parent corner'}).click();
    await parent.locator('#pin').fill('browser-private-passphrase');
    await parent.getByRole('button',{name:'Unlock', exact:true}).click();
    await parent.locator('#consentCheck').check();
    await parent.locator('#consentButton').click();
    await parent.locator('#newProfile').click();
    await parent.locator('#profileForm input[name=nickname]').fill('Nova');
    await parent.locator('#preset').selectOption('explorer');
    await parent.locator('#profileForm input[name=budget]').fill('120');
    await parent.locator('#profileForm input[name=require_approval]').uncheck();
    await parent.getByRole('button',{name:'Save profile',exact:true}).click();
    await parent.locator('#issuedCode').waitFor({state:'visible'});
    const code = await parent.locator('#issuedCode').textContent();
    assert(code.length>15);
    await parent.locator('#dismissCode').click();
    await parent.locator('#productForm input').fill('Building rocket');
    await parent.locator('#productForm button').click();
    const product = parent.locator('#parentCatalog article').filter({has:parent.getByRole('heading',{name:'Building rocket',exact:true})});
    await product.locator('.offer-editor input[type=url]').fill('https://www.amazon.com/dp/ROCKET');
    await product.locator('.offer-editor input[type=number]').fill('50');
    await product.locator('.offer-editor button').click();
    await product.locator('.offer').waitFor();
    await product.locator('.offer-editor').last().locator('input[type=url]').fill('https://www.walmart.com/ip/rocket/123');
    await product.locator('.offer-editor').last().locator('input[type=number]').fill('40.50');
    await product.locator('.offer-editor').last().locator('button').click();
    await product.getByText('$40.50',{exact:true}).waitFor();
    const child = await browser.newPage({viewport:{width:390,height:844}});
    child.on('pageerror', error => errors.push(error.message));
    await child.goto(base);
    await child.locator('#childCode').fill(code);
    await child.locator('#childLogin button').click();
    await child.locator('#kidCatalog').getByRole('button',{name:'Add to My Wish List'}).click();
    await child.locator('#budgetSummary').getByText('$40.50',{exact:true}).waitFor();
    assert((await child.locator('#budgetSummary').textContent()).includes('$79.50 remaining'));
    assert.equal(await child.locator('#kidCards .store-link').count(),2);
    await child.locator('#kidCards select').selectOption('Must Have');
    await child.locator('#kidCards select').waitFor();
    assert.equal(await child.locator('#kidCards select').inputValue(),'Must Have');
    assert(await child.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No mobile horizontal overflow');
    await child.screenshot({path:'/tmp/wish-child-mobile.png',fullPage:true});
    // Reload parent data without disturbing the child's session.
    await parent.locator('#allGifts').click();
    const gift = parent.locator('#parentCards article');
    await gift.getByRole('button',{name:'Reserve gift',exact:true}).click();
    await gift.getByText('Not purchased · Reserved',{exact:true}).waitFor();
    await gift.getByRole('button',{name:'Mark purchased',exact:true}).click();
    await gift.getByText('Purchased · Reserved',{exact:true}).waitFor();
    const actualForm = gift.locator('form').filter({hasText:'Actual paid'});
    await actualForm.locator('input').fill('20');
    const saveResponse = parent.waitForResponse(r => r.url().endsWith('/api/update') && r.request().method() === 'POST');
    await actualForm.getByRole('button',{name:'Save',exact:true}).click();
    const saved = await saveResponse; assert.equal(saved.status(),200,await saved.text());
    await gift.getByText('Savings vs. saved baseline: $20.50',{exact:true}).waitFor();
    await child.locator('#kidTab').click();
    await child.locator('#kidCards h3').waitFor();
    assert.equal(await child.locator('#kidCards h3').textContent(),'Building rocket');
    assert(!(await child.locator('#kidCards').textContent()).match(/purchased|reserved|actual paid|savings/i));
    assert((await child.locator('#budgetSummary').textContent()).includes('$40.50'));
    await parent.locator('#profiles').getByRole('button',{name:'Edit permissions & budget'}).click();
    await parent.locator('#profileForm input[name=show_prices]').uncheck();
    await parent.locator('#profileForm input[name=show_links]').uncheck();
    await parent.locator('#profileForm input[name=show_budget]').uncheck();
    await parent.getByRole('button',{name:'Save profile',exact:true}).click();
    await parent.locator('#profileDialog').waitFor({state:'hidden'});
    await child.locator('#kidTab').click();
    await child.getByText('Enjoy making your list. Prices are hidden by your parent’s settings.',{exact:true}).waitFor();
    assert.equal(await child.locator('#kidView a').count(),0);
    assert(!(await child.locator('#kidView').textContent()).includes('$'));
    assert.equal(await child.locator('#kidCards h3').textContent(),'Building rocket');
    assert.equal(await child.locator('#parentView').isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log('PASS: desktop parent setup, offers, mobile child budgets/comparison/priorities, private purchases, live permission changes; no browser errors.');
  } finally {
    if(browser)await browser.close();
    server.kill();
    await new Promise(r => server.once('close',r));
    rmSync(data,{recursive:true,force:true});
  }
})().catch(error => { console.error(error); process.exitCode=1; });
